/// Rejecting boundaries are installed before AppCoordinator is constructed.
/// No CaptureService, InferenceService, preferences or FunctionalQAFiles is made.
final class QARenderForbiddenCalls: @unchecked Sendable {
    private let lock = NSLock()
    private var storage: [String] = []
    var calls: [String] { lock.lock(); defer { lock.unlock() }; return storage }
    func reject(_ boundary: String) {
        lock.lock(); storage.append(boundary); lock.unlock()
        XCTFail("Forbidden offscreen-render boundary: \(boundary)")
    }
}

private final class RejectingRenderCapture: CaptureServicing, @unchecked Sendable {
    let forbidden: QARenderForbiddenCalls
    init(_ forbidden: QARenderForbiddenCalls) { self.forbidden = forbidden }
    func start(session: UUID, deviceID: AudioDeviceID?, channel: Int, policy: ResourcePolicy,
               authorization: CaptureStartupGate, onFirstSample: @escaping @Sendable () -> Void,
               onProgress: @escaping @Sendable (Double, Float) -> Void,
               onFailure: @escaping @Sendable (DictationError) -> Void,
               onLimitReached: @escaping @Sendable (CaptureStopRequest) -> Void) async throws {
        forbidden.reject("capture.start"); throw DictationError.privacyBlocked
    }
    func stop(_ request: CaptureStopRequest) async throws -> CapturedAudio {
        forbidden.reject("capture.stop"); throw DictationError.cancelled
    }
    func cancel(session: UUID?) async { forbidden.reject("capture.cancel") }
}

private final class RejectingRenderInference: InferenceServicing, @unchecked Sendable {
    let forbidden: QARenderForbiddenCalls
    init(_ forbidden: QARenderForbiddenCalls) { self.forbidden = forbidden }
    func load(url: URL, candidate: ModelCandidate) async throws -> (warm: Bool, seconds: Double) {
        forbidden.reject("inference.load"); throw DictationError.modelInvalid
    }
    func transcribe(_ pcm: SessionPCM, language: LanguageMode, cancellation: DecodeCancellation,
                    policy: ResourcePolicy) async throws -> TranscriptionResult {
        forbidden.reject("inference.decode"); throw DictationError.inferenceFailed
    }
    func unload() async { forbidden.reject("inference.unload") }
}

@MainActor final class QARenderIsolationFixture {
    static let transcript = "A quiet morning leaves room to think. The first idea becomes a clear sentence."
    static let longTranscript = Array(repeating: transcript, count: 45).joined(separator: "\n\n")
    let forbidden: QARenderForbiddenCalls
    let coordinator: AppCoordinator
    private let reviewText: FixtureValue<String>

    init() throws {
        let configuration = try AppLaunchConfiguration.parse(environment: [
            "CLAVUNE_QA_PROFILE": "isolated-content-render",
            "CLAVUNE_QA_FUNCTIONAL": "synthetic-v1",
        ], bundleIdentifier: nil)
        let forbidden = QARenderForbiddenCalls()
        let reviewText = FixtureValue("")
        self.forbidden = forbidden
        self.reviewText = reviewText
        let syntheticURL = URL(fileURLWithPath: "/synthetic-render-input-never-opened.txt")
        var environment = CoordinatorEnvironment(nowHostTime: { 100 },
            secureInputEnabled: { forbidden.reject("secureInput"); return true },
            permissionStatus: { forbidden.reject("permission.status"); return .denied },
            requestPermission: { forbidden.reject("permission.request"); return false },
            // The coordinator asks for its device-list value during construction.
            // This explicit empty value never enumerates host hardware.
            inputDevices: { [] },
            chooseModel: { forbidden.reject("model.picker"); return nil },
            makeCancellation: { forbidden.reject("native.cancellation"); throw DictationError.cancelled },
            makeWatchdog: { _ in forbidden.reject("watchdog"); return {} },
            workspaceNotifications: nil,
            terminate: { forbidden.reject("terminate") },
            registerHotkey: { _, _ in forbidden.reject("globalHotkey"); throw DictationError.privacyBlocked },
            quitWillAwaitAdmittedOperation: { forbidden.reject("quit") },
            quitWillUnloadInference: { forbidden.reject("quit.unload") })
        environment.copyText = { _ in forbidden.reject("clipboard"); return false }
        environment.chooseTranscriptToOpen = { _ in syntheticURL }
        environment.chooseTranscriptToSave = { _ in forbidden.reject("save.picker"); return nil }
        environment.readTranscript = { url in
            guard url == syntheticURL else {
                forbidden.reject("transcript.read-unrecognized-URL"); throw DictationError.cancelled
            }
            return reviewText.value // Generated bytes only; the URL is never opened.
        }
        environment.writeTranscript = { _, _ in forbidden.reject("transcript.write"); throw DictationError.cancelled }
        environment.chooseAudioToImport = { _ in forbidden.reject("audio.picker"); return nil }
        environment.readAudio = { _, _ in forbidden.reject("audio.read"); throw DictationError.cancelled }
        environment.importManagedModel = { _ in forbidden.reject("model.import"); throw DictationError.modelInvalid }
        environment.restoreManagedSelection = { _ in forbidden.reject("model.restore"); throw DictationError.modelInvalid }
        environment.downloadManagedModel = { _, _ in forbidden.reject("network.download"); throw DictationError.modelInvalid }
        environment.confirmTranscriptReplacement = { _ in forbidden.reject("replace.dialog"); return false }
        environment.confirmUnsavedReviewQuit = { _ in forbidden.reject("quit.dialog"); return .cancel }
        coordinator = AppCoordinator(policy: try ResourcePolicy.bundled(),
            capture: RejectingRenderCapture(forbidden), inference: RejectingRenderInference(forbidden),
            environment: environment, preferences: nil, launchConfiguration: configuration,
            modelSelection: nil, localMetricsJournal: nil,
            processUsageSnapshot: { forbidden.reject("process.usage"); return nil })
    }

    /// Exercise the real document admission/transition with an injected memory
    /// reader, never a file. The renderer awaits the admitted task before capture.
    func openReview(_ text: String) {
        reviewText.value = text
        coordinator.openTranscript()
    }

    func assertSafe(file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertEqual(forbidden.calls, [], file: file, line: line)
        XCTAssertEqual(coordinator.microphone.state, .closed, file: file, line: line)
        XCTAssertFalse(coordinator.operationPending, file: file, line: line)
        XCTAssertFalse(coordinator.closePending, file: file, line: line)
        XCTAssertFalse(coordinator.canStart, "Preview must not imply recording admission", file: file, line: line)
        XCTAssertTrue(coordinator.launchConfiguration.isQA, file: file, line: line)
    }
}
